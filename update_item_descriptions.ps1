$files = Get-ChildItem -Path $ItemsFolder -Filter '*.asset' -File -Recurse
$updatedCount = 0
$missingNames = @()

foreach ($file in $files) {
    $lines = Get-Content -LiteralPath $file.FullName
    $itemName = $null
    for ($i = 0; $i -lt $lines.Length; $i++) {
        if ($lines[$i] -match '^\s*itemName:\s*(.+)$') {
            $itemName = $matches[1].Trim()
            break
        }
    }

    if (-not $itemName) {
        continue
    }

    if (-not $descriptionByItemName.ContainsKey($itemName)) {
        continue
    }

    $newDescription = $descriptionByItemName[$itemName]
    $descLineIndex = $null
    for ($j = 0; $j -lt $lines.Length; $j++) {
        if ($lines[$j] -match '^\s*description:\s*(.*)$') {
            $descLineIndex = $j
            break
        }
    }

    if ($null -eq $descLineIndex) {
        $missingNames += $itemName
        continue
    }

    $existingLine = $lines[$descLineIndex]
    $replacement = "  description: $newDescription"
    if ($existingLine -ne $replacement) {
        $lines[$descLineIndex] = $replacement
        Set-Content -LiteralPath $file.FullName -Value $lines -Encoding UTF8
        $updatedCount++
        Write-Host "Updated description for '$itemName' in $($file.Name)"
    }
}

Write-Host "Descriptions updated: $updatedCount"

if ($missingNames.Count -gt 0) {
    Write-Warning "Items missing description field: $($missingNames | Sort-Object -Unique -join ', ')"
}
